const vm = require('node:vm');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const node = () => ({ style:{}, getBoundingClientRect:()=>({left:0,top:0,width:100}), setAttribute(){}, appendChild(){}, innerHTML:'', textContent:'', remove(){} });
const nodes = {};
const context = vm.createContext({window:{}, document:{getElementById:id => nodes[id] ||= node(), querySelectorAll:()=>[], createElement:node, body:node()}, setTimeout:()=>{}, Math});
vm.runInContext(fs.readFileSync(`${__dirname}/game.js`, 'utf8'), context);
const run = code => vm.runInContext(code,context);
let count = 0;
function test(name, code, expected) { run('restartGame()'); assert.equal(run(code), expected, name); count++; }
test('attack', "playerCast('STU'); aiHp",80);
test('double click blocked', "playerCast('STU');playerCast('INC');aiHp",80);
test('invalid key ignored', "playerCast('bad');phase",'player');
test('shield reflection', "isAiShield=true;playerCast('INC');playerHp",70);
test('shield consumed', "isAiShield=true;playerCast('INC');isAiShield",false);
test('healing capped', "playerHp=90;playerCast('EPI');playerHp",100);
test('AK halves rounded', "aiHp=51;playerCast('AK');aiHp",26);
test('AK cannot kill', "aiHp=1;playerCast('AK');aiHp",1);
test('full three cooldown turns', "playerCast('AK');for(let i=0;i<3;i++){phase='player';playerCast('PRO')}akCd",0);
test('cooldown blocks AK', "akCd=2;playerCast('AK');phase",'player');
test('AI waits for continue', "playerCast('STU');phase",'ai-ready');
test('AI blocked after restart', "playerCast('STU');restartGame();aiTurn();playerHp",100);
test('one score only', "aiHp=20;playerCast('STU');checkWin();playerScore",1);
test('four wins retained', "playerScore=3;aiHp=20;playerCast('STU');continueGame();phase+':'+playerScore",'match-end:4');
test('next round retains score', "aiHp=20;playerCast('STU');continueGame();playerScore+':'+aiHp",'1:100');
test('AI reflection can lose', "phase='ai-ready';aiHp=20;isPlayerShield=true;cast('STU',false);checkWin();playerScore",1);
console.log(`${count} tests passed`);
